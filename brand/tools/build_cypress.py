# ---- colour ----------------------------------------------------------------
def rgb(h): h = h.lstrip('#'); return [int(h[i:i + 2], 16) for i in (0, 2, 4)]
def hx(c): return '#' + ''.join(f'{max(0, min(255, round(v))):02X}' for v in c)
def mix(a, b, pct):  # same as CSS color-mix(in srgb, a pct%, b)
    A, B = rgb(a), rgb(b); t = pct / 100; return hx([A[i] * t + B[i] * (1 - t) for i in range(3)])
def lum(h):
    def ch(v):
        v /= 255; return v / 12.92 if v <= .03928 else ((v + .055) / 1.055) ** 2.4
    r, g, b = (ch(v) for v in rgb(h)); return .2126 * r + .7152 * g + .0722 * b
def ratio(a, b):
    x, y = sorted([lum(a), lum(b)], reverse=True); return (x + .05) / (y + .05)

