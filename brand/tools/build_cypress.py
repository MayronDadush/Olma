def write_ase(path, groups):
    blocks = []
    def nb(s): s += '\0'; return struct.pack('>H', len(s)) + s.encode('utf-16-be')
    for g, items in groups:
        n = nb('Allma ' + g); blocks.append(struct.pack('>HI', 0xC001, len(n)) + n)
        for name, h in items:
            r, gg, b = (c / 255 for c in rgb(h))
            body = nb(name) + b'RGB ' + struct.pack('>fffH', r, gg, b, 2)
            blocks.append(struct.pack('>HI', 0x0001, len(body)) + body)
        blocks.append(struct.pack('>HI', 0xC002, 0))
    with open(path, 'wb') as f: f.write(b'ASEF' + struct.pack('>HHI', 1, 0, len(blocks)) + b''.join(blocks))

