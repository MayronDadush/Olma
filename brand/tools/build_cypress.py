def lens(cx1, cx2, cy, r):
    h = math.sqrt(r * r - ((cx2 - cx1) / 2) ** 2); x = (cx1 + cx2) / 2
    return f'M{x} {cy - h:.2f}A{r} {r} 0 0 1 {x} {cy + h:.2f}A{r} {r} 0 0 1 {x} {cy - h:.2f}Z'

